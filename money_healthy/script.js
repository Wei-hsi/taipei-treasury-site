const YI = 1e8; // 1 億 = 100,000,000
const toYi = (yuan) => yuan / YI;
const comma = (v) => Math.round(Number(v) || 0).toLocaleString('en-US');
const yi1 = (yuan) => (yuan / YI).toFixed(1);
const yi0 = (yuan) => comma(Math.round(yuan / YI));
const pct1 = (v) => (Number(v) || 0).toFixed(1) + '%';

function isDark() {
  return matchMedia('(prefers-color-scheme: dark)').matches;
}
function theme() {
  const dark = isDark();
  const css = getComputedStyle(document.documentElement);
  const v = (n) => css.getPropertyValue(n).trim();
  return {
    ink: dark ? '#e7edf4' : '#1a2430',
    sub: dark ? '#a9b6c4' : '#5a6877',
    grid: dark ? '#283543' : '#e8ebf0',
    surface: dark ? '#18222e' : '#ffffff',
    palette: [v('--c1'), v('--c2'), v('--c3'), v('--c4'), v('--c5'), v('--c6'), v('--c7'), v('--c8')],
    brand: v('--brand') || '#0B3D6B',
    gold: v('--gold') || '#C8A04B',
    pos: v('--pos') || '#1d9e75',
    neg: v('--neg') || '#c0433b',
  };
}

